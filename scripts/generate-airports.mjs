#!/usr/bin/env node
// Regenerates src/data/airports.ts from the OurAirports public-domain
// airports.csv (Unlicense — no attribution required). Run manually at
// data-prep time; the app does not fetch this at runtime or at build time.
//
// Usage: node scripts/generate-airports.mjs
//
// Source: https://davidmegginson.github.io/ourairports-data/airports.csv
// Fallback source (if the above is unreachable): https://ourairports.com/data/airports.csv

const PRIMARY_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const FALLBACK_URL = "https://ourairports.com/data/airports.csv";
const OUTPUT_PATH = new URL("../src/data/airports.ts", import.meta.url);

// Preference order when two rows share an iata_code (rare, but the dataset
// does not guarantee uniqueness): larger/more-official airport types win.
const TYPE_RANK = {
  large_airport: 0,
  medium_airport: 1,
  small_airport: 2,
  seaplane_base: 3,
  balloonport: 4,
  heliport: 5,
  closed: 6,
};

// Minimal RFC4180-ish CSV line parser: handles quoted fields containing
// commas and escaped ("") quotes. OurAirports' airports.csv has no embedded
// newlines within fields, so a line-based parse is sufficient here.
function parseCsvLine(line) {
  const fields = [];
  let current = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];

    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        current += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      fields.push(current);
      current = "";
    } else {
      current += ch;
    }
  }

  fields.push(current);
  return fields;
}

async function fetchCsv() {
  for (const url of [PRIMARY_URL, FALLBACK_URL]) {
    try {
      const response = await fetch(url);

      if (response.ok) {
        console.log(`Fetched airport data from ${url}`);
        return await response.text();
      }

      console.warn(`Fetch failed (${response.status}) from ${url}`);
    } catch (error) {
      console.warn(`Fetch error from ${url}:`, error);
    }
  }

  throw new Error("Could not fetch airports.csv from primary or fallback source.");
}

function escapeForTsString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

async function main() {
  const csv = await fetchCsv();
  const lines = csv.split("\n").filter((line) => line.length > 0);
  const header = parseCsvLine(lines[0]);
  const col = Object.fromEntries(header.map((name, index) => [name, index]));
  const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

  function countryName(isoCountry) {
    if (!isoCountry) return "";

    try {
      return regionNames.of(isoCountry) ?? isoCountry;
    } catch {
      return isoCountry;
    }
  }

  const byIata = new Map();
  const collisions = [];
  const closedOrHeliportIncluded = [];

  for (let i = 1; i < lines.length; i++) {
    const fields = parseCsvLine(lines[i]);
    const iataCode = fields[col.iata_code]?.trim();

    if (!iataCode) continue;

    const type = fields[col.type]?.trim();
    const row = {
      code: iataCode.toUpperCase(),
      name: fields[col.name]?.trim() ?? "",
      city: fields[col.municipality]?.trim() ?? "",
      country: countryName(fields[col.iso_country]?.trim()),
      type,
    };

    if (type === "closed" || type === "heliport") {
      closedOrHeliportIncluded.push({ code: row.code, name: row.name, type });
    }

    const existing = byIata.get(row.code);

    if (!existing) {
      byIata.set(row.code, row);
      continue;
    }

    collisions.push({ code: row.code, existingType: existing.type, incomingType: row.type });

    if ((TYPE_RANK[row.type] ?? 9) < (TYPE_RANK[existing.type] ?? 9)) {
      byIata.set(row.code, row);
    }
  }

  const airports = [...byIata.values()]
    .map(({ code, name, city, country }) => ({ code, name, city, country }))
    .sort((a, b) => a.code.localeCompare(b.code));

  const today = new Date().toISOString().slice(0, 10);
  const body = airports
    .map(
      (a) =>
        `  { code: "${a.code}", name: "${escapeForTsString(a.name)}", city: "${escapeForTsString(
          a.city,
        )}", country: "${escapeForTsString(a.country)}" },`,
    )
    .join("\n");

  const output = `// Generated by scripts/generate-airports.mjs from OurAirports' airports.csv
// (public domain / Unlicense — no attribution required) as of ${today}.
// Do not edit by hand — re-run the generator script to refresh this file.
import type { Airport } from "@/types/airports";

export const AIRPORTS: Airport[] = [
${body}
];
`;

  const fs = await import("node:fs/promises");
  await fs.writeFile(OUTPUT_PATH, output);

  console.log(`Wrote ${airports.length} airports to ${OUTPUT_PATH.pathname}`);
  console.log(`IATA-code collisions resolved: ${collisions.length}`);

  if (collisions.length > 0) {
    console.log(JSON.stringify(collisions, null, 2));
  }

  console.log(
    `closed/heliport rows included (non-empty iata_code): ${closedOrHeliportIncluded.length}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
